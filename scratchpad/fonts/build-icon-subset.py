# Build the app's own copy of the Tabler icon font holding ONLY the icons the provider app uses
# (2026-11-07, "app load times are still quite slow"). The app used to load the whole set from
# jsDelivr: a render-blocking stylesheet from another server (237 KB) plus an 865 KB font for ~5,900
# icons, of which it uses a few hundred. Now: the rules are inlined in slickchart.html between the
# ICON-SUBSET markers and the font is /assets/fonts/tabler-<hash>.woff2 on our own server (immutable).
#   python3 scratchpad/fonts/build-icon-subset.py <tabler-icons.min.css 3.19.0> <tabler-icons.woff2 3.19.0>
# Re-run it after adding an icon; scripts/check-icon-subset.cjs (CI) fails the build until you do.
# Names come from every `ti-NAME` in the source AND every quoted word that is an icon name, because
# the app builds some classes as ti-${cond?'check':'x'}.
import re, sys, hashlib, os, glob
css_path, font_path = sys.argv[1], sys.argv[2]
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'slickchart-vercel')
html_path = os.path.join(root, 'slickchart.html')
css = open(css_path, encoding='utf-8').read()
icons = dict(re.findall(r'\.ti-([a-z0-9-]+):before\{content:"\\([0-9a-f]+)"\}', css))
src = open(html_path, encoding='utf-8').read()
start, end = '/* ICON-SUBSET:START', '/* ICON-SUBSET:END */'
if start in src:
    a = src.index(start); b = src.index(end) + len(end); scan = src[:a] + src[b:]
else:
    scan = src
# The public demos are built from this same page with the sample data in demo-seed*.js.
for extra in ('demo-seed-client.js', os.path.join('scripts', 'demo-seed.js')):
    ep = os.path.join(root, extra)
    if os.path.exists(ep): scan += open(ep, encoding='utf-8').read()
# Every icon name, for scripts/check-icon-subset.cjs (which has no font tools).
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'tabler-3.19.0-names.txt'), 'w').write('\n'.join(sorted(icons)) + '\n')
used = set(re.findall(r'ti-([a-z0-9]+(?:-[a-z0-9]+)*)', scan)) & set(icons)
used |= set(re.findall(r'''['"`]([a-z0-9]+(?:-[a-z0-9]+)*)['"`]''', scan)) & set(icons)
names = sorted(used)
cps = sorted({icons[n] for n in names})
out_dir = os.path.join(root, 'assets', 'fonts'); os.makedirs(out_dir, exist_ok=True)
tmp = os.path.join(out_dir, '_tabler-tmp.woff2')
# The upstream font's ligature table (GSUB) does not load in fontTools, and icons by class name never
# use ligatures, so it is dropped before subsetting.
from fontTools.ttLib import TTFont
from fontTools import subset as fts
f = TTFont(font_path)
for t in ('GSUB', 'GPOS', 'GDEF'):
    if t in f: del f[t]
opts = fts.Options(); opts.flavor = 'woff2'; opts.layout_features = []; opts.hinting = False; opts.notdef_outline = True
sub = fts.Subsetter(opts); sub.populate(unicodes=[int(c, 16) for c in cps]); sub.subset(f)
f.flavor = 'woff2'; f.save(tmp)
h = hashlib.sha256(open(tmp, 'rb').read()).hexdigest()[:12]
fname = 'tabler-' + h + '.woff2'
for old in glob.glob(os.path.join(out_dir, 'tabler-*.woff2')):
    if os.path.basename(old) != fname: os.remove(old)
os.replace(tmp, os.path.join(out_dir, fname))
base = re.search(r'\.ti\{[^}]*\}', css).group(0)
block = (start + ' generated by scratchpad/fonts/build-icon-subset.py from Tabler Icons 3.19.0 (MIT): '
         + str(len(names)) + ' icons. Do not edit by hand. */\n'
         + '@font-face{font-family:"tabler-icons";font-style:normal;font-weight:400;font-display:block;src:url("/assets/fonts/' + fname + '") format("woff2")}'
         + base + ''.join('.ti-%s:before{content:"\\%s"}' % (n, icons[n]) for n in names) + '\n' + end)
if start in src:
    a = src.index(start); b = src.index(end) + len(end); src = src[:a] + block + src[b:]
else:
    raise SystemExit('add the ICON-SUBSET markers inside the first <style> first')
# The preload in <head> names the same file, so the icons start downloading before the CSS is read.
src = re.sub(r'href="/assets/fonts/tabler-[a-f0-9]+\.woff2"', 'href="/assets/fonts/' + fname + '"', src)
open(html_path, 'w', encoding='utf-8').write(src)
print('%d icons, font %s (%d bytes)' % (len(names), fname, os.path.getsize(os.path.join(out_dir, fname))))
