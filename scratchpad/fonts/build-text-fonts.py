# Self-host the app's two text fonts (DM Sans, Cormorant Garamond; both SIL Open Font License) instead
# of a render-blocking stylesheet from fonts.googleapis.com that a phone had to re-check every day
# before it could draw anything (2026-11-07). Latin and Latin-extended only, as Google serves them.
#   python3 scratchpad/fonts/build-text-fonts.py <google css2 response, fetched with a Chrome UA>
import re, sys, os, hashlib, urllib.request
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'slickchart-vercel')
css = open(sys.argv[1], encoding='utf-8').read()
out_dir = os.path.join(root, 'assets', 'fonts'); os.makedirs(out_dir, exist_ok=True)
blocks = re.findall(r'/\* ([a-z-]+) \*/\s*@font-face \{(.*?)\}', css, re.S)
faces, got = [], {}
for subset, body in blocks:
    if subset not in ('latin', 'latin-ext'): continue
    fam = re.search(r"font-family: '([^']+)'", body).group(1)
    w = re.search(r'font-weight: (\d+)', body).group(1)
    url = re.search(r'url\((https://[^)]+)\)', body).group(1)
    ur = re.search(r'unicode-range: ([^;]+);', body).group(1)
    if url not in got:
        data = urllib.request.urlopen(url).read()
        name = '%s-%s-%s.woff2' % (fam.lower().replace(' ', '-'), subset, hashlib.sha256(data).hexdigest()[:10])
        open(os.path.join(out_dir, name), 'wb').write(data); got[url] = name
    faces.append("@font-face{font-family:'%s';font-style:normal;font-weight:%s;font-display:swap;src:url(/assets/fonts/%s) format('woff2');unicode-range:%s}" % (fam, w, got[url], ur))
start, end = '/* TEXT-FONTS:START', '/* TEXT-FONTS:END */'
block = start + ' generated by scratchpad/fonts/build-text-fonts.py (SIL OFL fonts, self-hosted). */\n' + '\n'.join(faces) + '\n' + end
p = os.path.join(root, 'slickchart.html'); src = open(p, encoding='utf-8').read()
a = src.index(start); b = src.index(end) + len(end)
open(p, 'w', encoding='utf-8').write(src[:a] + block + src[b:])
print(len(faces), 'faces,', len(got), 'files:', ', '.join(sorted(got.values())))
