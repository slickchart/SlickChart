// api/cron-checkins.js (2026-11-18 capacity review): providers are worked a few at a time, every
// provider still gets its check-ins, each with ITS OWN Square token and clients, exactly once.
import fs from 'fs'; import os from 'os'; import path from 'path';
const V = new URL('../slickchart-vercel/', import.meta.url).pathname;
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'cci-')); fs.mkdirSync(root + '/lib'); fs.mkdirSync(root + '/api');
fs.writeFileSync(root + '/package.json', '{"type":"module"}');
fs.copyFileSync(V + 'api/cron-checkins.js', root + '/api/cron-checkins.js');
const N = 40;
fs.writeFileSync(root + '/lib/db.js', `export const dbEnabled=()=>true; export const getKVValue=async()=>null;
export function sql(){ return async (s,...v)=>{ const t=s.join('?');
  if(/FROM square_connections/.test(t)) return Array.from({length:${N}},(_,i)=>({provider_id:'p'+i}));
  if(/FROM clients WHERE provider_id/.test(t)) return [{id:'c-'+v[0], token:'tok-'+v[0], email:v[0]+'@client.test', phone:'', opened_at:1}];
  return []; }; }`);
fs.writeFileSync(root + '/lib/clients.js', `export const LOGGED=[]; const seen=new Set();
export const ensureClientTables=async()=>{}; export const claimReminder=async(c,k)=>{ const key=c+'|'+k; if(seen.has(key)) return false; seen.add(key); return true; };
export const logEvent=async(o,c,k,p)=>{ LOGGED.push({o,c}); }; export const listPushSubs=async()=>[]; export const deletePushSub=async()=>{};
export const spaceUrl=t=>'/space/'+t; export const wantsPush=async()=>false;`);
fs.writeFileSync(root + '/lib/square.js', `export let INFLIGHT=0, PEAK=0; export const CALLS=[];
export const refreshExpiringConnections=async()=>0; export const getConnection=async p=>({token:'T-'+p});
export async function squareFetch(u,o,tok){ INFLIGHT++; PEAK=Math.max(PEAK,INFLIGHT); CALLS.push({u,tok}); await new Promise(r=>setTimeout(r,40)); INFLIGHT--;
  const p=tok.slice(2);
  if(u.startsWith('/v2/locations')) return {locations:[{id:'L-'+p,timezone:'UTC'}]};
  if(u.startsWith('/v2/bookings')) return {bookings:[{id:'B-'+p,status:'ACCEPTED',customer_id:'CU-'+p,start_at:new Date(Date.now()+5*3600e3).toISOString(),location_id:'L-'+p}]};
  if(u.startsWith('/v2/customers/')) return {customer:{email_address:p+'@client.test'}};
  return {}; }`);
fs.writeFileSync(root + '/lib/push.js', 'export const pushConfigured=()=>false; export const sendPushToAll=async()=>0;');
fs.writeFileSync(root + '/lib/fcm.js', 'export const nativePushConfigured=()=>false; export const sendNativeToClient=async()=>0;');
fs.writeFileSync(root + '/lib/cron-runs.js', 'export const withCronRun=(n,h)=>h;');
process.env.CRON_SECRET = 's';
const C = await import(root + '/lib/clients.js'), S = await import(root + '/lib/square.js');
const run = (await import(root + '/api/cron-checkins.js')).default;
const res = { status(c) { this.c = c; return this; }, json(b) { this.b = b; return this; } };
const t0 = Date.now(); await run({ method: 'GET', headers: { authorization: 'Bearer s' }, query: {} }, res); const ms = Date.now() - t0;
let pass = 0, fail = 0; const check = (n, ok, d) => { console.log((ok ? 'PASS ' : 'FAIL ') + n + (ok ? '' : ' — ' + JSON.stringify(d))); ok ? pass++ : fail++; };
check('ran OK', res.c === 200 && res.b.ok, res.b);
check('every provider got its check-in', C.LOGGED.length === N && new Set(C.LOGGED.map(x => x.o)).size === N, C.LOGGED.length);
check('each went to that provider\'s own client', C.LOGGED.every(x => x.c === 'c-' + x.o));
check('each provider\'s Square calls used its own token', S.CALLS.every(c => c.u.startsWith('/v2/locations') || c.u.includes(c.tok.slice(2)) || c.u.startsWith('/v2/bookings?start')), S.CALLS.slice(0, 3));
check('a few at a time, never all at once', S.PEAK > 1 && S.PEAK <= 6, S.PEAK);
check('faster than one by one (' + ms + ' ms)', ms < N * 4 * 40 / 2, ms);
await run({ method: 'GET', headers: { authorization: 'Bearer s' }, query: {} }, res);
check('a second run sends nothing twice', C.LOGGED.length === N, C.LOGGED.length);
console.log('\n' + pass + '/' + (pass + fail) + ' passed'); process.exit(fail ? 1 : 0);
